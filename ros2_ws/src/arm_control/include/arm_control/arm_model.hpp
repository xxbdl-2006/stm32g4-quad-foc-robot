// ============================================================================
//  arm_model.hpp
//  HWB-ARM4 —— 四自由度 SCARA 型协作机械臂的几何与索引约定。
//
//  索引约定（全工程强制统一，改一处必须同步全部）
//  ---------------------------------------------------------------
//     0 = J1  基座回转    revolute  ∥ Z
//     1 = J2  大臂回转    revolute  ∥ Z
//     2 = J3  小臂回转    revolute  ∥ Z
//     3 = J4  升降        prismatic ∥ Z（由无刷电机 + 滚珠丝杠驱动）
//
//  这个顺序同时是：CAN 帧的 IDX、MotorCommandArray / MotorStateArray 的下标、
//  运动学的关节数组下标、URDF 里 joint_1..joint_4、固件里的 g_motors[]。
//  任何一处错位都会表现成"某个关节按别的关节的指令动"，这种 bug 在实机上
//  极难定位（尤其是 J1/J2 对调时，末端还是能到目标点附近的）。
//
//  为什么 J4 是直线轴却接在旋转伺服驱动板上
//  ----------------------------------------
//  驱动板不区分关节类型，它只知道"某个轴转了多少弧度"。J4 用无刷电机 +
//  滚珠丝杠（导程 lead）把转角线性映射成直线位移，映射关系放在**上位机**：
//      d4 [m] = q4_motor [rad] * lead / (2π)
//  这样做的原因有两个：
//    · 驱动板不需要增加"直线轴"这种新概念，CAN 协议与固件一行都不用改；
//    · 换丝杠导程（比如从 10mm 换成 5mm 做更精细的升降）只需要改上位机
//      参数，不用重新烧固件。
//  代价是驱动板侧的"位置 mrad"对 J4 而言是丝杠转角，看波形时要心里有数。
// ============================================================================
#ifndef ARM_CONTROL__ARM_MODEL_HPP_
#define ARM_CONTROL__ARM_MODEL_HPP_

#include <cstdint>

namespace arm_control
{

/// 关节索引。所有数组、CAN 帧、URDF 关节名都按这个顺序。
enum JointIndex : int
{
  kJ1Base     = 0,   ///< 基座回转
  kJ2Shoulder = 1,   ///< 大臂回转
  kJ3Elbow    = 2,   ///< 小臂回转
  kJ4Lift     = 3,   ///< 升降（直线轴）
  kJointCount = 4,
};

/// 关节名（与 URDF 中 <joint name="..."> 一致）
inline const char * joint_name(int i)
{
  switch (i) {
    case kJ1Base:     return "joint_1";
    case kJ2Shoulder: return "joint_2";
    case kJ3Elbow:    return "joint_3";
    case kJ4Lift:     return "joint_4";
    default:          return "joint_?";
  }
}

/// 关节的物理性质（直线轴 / 旋转轴）。给关节限位的单位解释用。
inline bool is_prismatic(int i) { return i == kJ4Lift; }

// ---------------------------------------------------------------------------
//  机构尺寸
//
//  数值来源：机械图纸实测（2025-09 定型的第二版样机）。每一项都注明它是
//  "哪一段"，因为 a1/a2 搞反是这类机械臂最容易犯也最难查的错 —— 表现是
//  末端总差一个固定向量，而 IK 的残差看起来"收敛得很好"。
// ---------------------------------------------------------------------------
struct ArmGeometry
{
  /// 大臂长度：J1 回转轴 -> J2 回转轴（m）
  double a1{0.180};
  /// 小臂长度：J2 回转轴 -> J3 回转轴（m）
  double a2{0.180};
  /// 腕部偏移：J3 回转轴 -> 吸盘中心（m）
  double a3{0.060};
  /// 基座高度：工作台面 -> J1/J2 回转平面（m）
  double d1{0.140};
  /// 升降丝杠导程（m/rev）。J4 是 10mm 导程的滚珠丝杠，电机直连无减速。
  double lead{0.010};

  /// 最大工作半径（三个连杆完全伸直时）
  double reach_max() const { return a1 + a2 + a3; }

  /**
   * @brief 最小工作半径。
   *
   * 当大臂"折回来"时，末端能到的最小半径是 |a1 - (a2 + a3)|。本机构是
   * a2+a3 = 0.24 > a1 = 0.18，所以理论最小半径是 0.06 m —— 但这只是
   * 几何上的可达，实际取 0.10 m 作为下限：再往里走，小臂会与大臂、
   * 基座外壳发生干涉（机械上有 Φ120 的基座法兰）。
   */
  double reach_min() const { return 0.100; }
};

// ---------------------------------------------------------------------------
//  关节限位
//
//  旋转轴单位 rad（输出轴侧，三个回转轴经谐波减速器 1:50，编码器装在电机侧，
//  驱动板报的是折算后的输出轴角度）；
//  J4 是直线轴，限位单位 m。
//
//  J4 行程的基准点必须说清楚，否则"够不到台面"这种问题会一路带到实机：
//      d4 = 0        吸盘中心与肩关节平面等高（丝杠滑块在最上端，机械限位）
//      d4 = -0.135   吸盘中心降到台面上方 5mm（d1 = 140mm → z = 5mm）
//  也就是 **Z 轴只能往下走**，行程 135mm。这是 SCARA 的常规布置：滑块
//  在断电时靠自重停在下端或由抱闸保持在原位，上限做成机械死挡更安全。
//  一开始把行程写成 ±40mm 就出过问题 —— 那样吸盘永远停在台面上方 60mm
//  以上，运动学全部正常，但实机根本够不到物块。
// ---------------------------------------------------------------------------
struct JointLimits
{
  double lo[kJointCount]{-3.14159265358979323846, -2.6179938779914944,
                         -2.6179938779914944, -0.135};
  double hi[kJointCount]{ 3.14159265358979323846,  2.6179938779914944,
                          2.6179938779914944,  0.000};

  bool within(int i, double q) const
  {
    return (i >= 0 && i < kJointCount) ? (q >= lo[i] && q <= hi[i]) : false;
  }
};

// ---------------------------------------------------------------------------
//  J4 直线轴 <-> 丝杠转角 的换算
// ---------------------------------------------------------------------------
inline double lift_to_motor_rad(double d4_m, double lead)
{
  return d4_m * 2.0 * 3.14159265358979323846 / lead;
}

inline double motor_rad_to_lift(double q4_rad, double lead)
{
  return q4_rad * lead / (2.0 * 3.14159265358979323846);
}

}  // namespace arm_control

#endif  // ARM_CONTROL__ARM_MODEL_HPP_
